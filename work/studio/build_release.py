from pathlib import Path
import subprocess,sys,shutil,pefile,json
from build_info import source_identity,APP_VERSION
root=Path(__file__).resolve().parent
workspace=root.parent.parent
identity=source_identity(root)
try:
    git_root=Path(__import__('os').environ.get('COLOR_STUDIO_GIT_ROOT',str(workspace)))
    identity['git_commit']=subprocess.check_output(['git','rev-parse','HEAD'],cwd=git_root,
        text=True,stderr=subprocess.DEVNULL).strip()
except (OSError,subprocess.SubprocessError):identity['git_commit']=None
build_info=root/'bundle/build-info.json';build_info.parent.mkdir(parents=True,exist_ok=True)
build_info.write_text(json.dumps(identity,indent=2),encoding='utf-8')
ocr=root/'bundle/ocr';ocr.mkdir(parents=True,exist_ok=True)
source=Path(__import__('os').environ.get('TESSERACT_HOME','C:/Program Files/Tesseract-OCR'))
if not (source/'tesseract.exe').exists():raise SystemExit('Install Tesseract OCR or set TESSERACT_HOME first.')
todo=[source/'tesseract.exe'];seen=set()
while todo:
 p=todo.pop()
 if p.name.lower() in seen:continue
 seen.add(p.name.lower())
 target=ocr/p.name
 if p.resolve()!=target.resolve():shutil.copy2(p,target)
 pe=pefile.PE(str(p))
 for entry in getattr(pe,'DIRECTORY_ENTRY_IMPORT',[]):
  dependency=source/entry.dll.decode()
  if dependency.exists():todo.append(dependency)
 pe.close()
(ocr/'tessdata').mkdir(exist_ok=True)
traineddata=source/'tessdata/eng.traineddata';bundled_traineddata=ocr/'tessdata/eng.traineddata'
if traineddata.resolve()!=bundled_traineddata.resolve():shutil.copy2(traineddata,bundled_traineddata)
out=Path(__import__('os').environ.get('COLOR_STUDIO_DIST',str(workspace/'outputs/release')))
trust_path=__import__('os').environ.get('COLOR_STUDIO_UPDATE_PUBLIC_KEYS')
trust_args=[]
if trust_path:
    trusted=json.loads(Path(trust_path).read_text(encoding='utf-8'))
    if not isinstance(trusted,dict) or not trusted or any(len(bytes.fromhex(v))!=32 for v in trusted.values()):raise SystemExit('Invalid release public keys')
    bundled_trust=root/'bundle/update-trust.json';bundled_trust.write_text(json.dumps(trusted,sort_keys=True),encoding='utf-8')
    trust_args=['--add-data',str(bundled_trust)+';.']
subprocess.run([sys.executable,'-m','PyInstaller','--noconfirm','--onefile','--windowed','--name','ColorStudioUpdater',
    '--distpath',str(out/'helper'),'--workpath',str(root/'build-updater'),'--specpath',str(root),
    '--exclude-module','numpy','--exclude-module','cv2','--exclude-module','customtkinter',*trust_args,str(root/'update_helper.py')],check=True)
import hashlib
recovery_identity=root/'update_recovery_identity.py'
original_recovery_source=recovery_identity.read_text(encoding='utf-8')
recovery_identity.write_text('"""Embedded independent recovery helper identity; generated by build_release."""\nHELPER_SHA256='+repr(hashlib.sha256((out/'helper/ColorStudioUpdater.exe').read_bytes()).hexdigest())+'\n',encoding='utf-8')
identity=source_identity(root)
identity['git_commit']=subprocess.check_output(['git','rev-parse','HEAD'],cwd=git_root,text=True,stderr=subprocess.DEVNULL).strip()
build_info.write_text(json.dumps(identity,indent=2),encoding='utf-8')
saved=out/'ColorStudio/data'
if saved.exists():
    # Keep a local backup for development, but never carry personal sessions,
    # profiles or screenshots into a distributable package.
    shutil.copytree(saved,root/'release-test-data',dirs_exist_ok=True)
    shutil.rmtree(saved)
try:
    subprocess.run([sys.executable,'-m','PyInstaller','--noconfirm','--onedir','--windowed','--name','ColorStudio','--distpath',str(out),'--workpath',str(root/'build'),'--specpath',str(root),'--collect-data','customtkinter','--collect-data','opencc','--add-data',str(ocr)+';ocr','--add-data',str(build_info)+';.','--add-data',str(root/'native_live/assets')+';native_live/assets','--exclude-module','PySide6','--exclude-module','pandas','--exclude-module','matplotlib',*trust_args,str(root/'app.py')],check=True)
finally:recovery_identity.write_text(original_recovery_source,encoding='utf-8')
shutil.copy2(out/'helper/ColorStudioUpdater.exe',out/'ColorStudio/ColorStudioUpdater.exe')
# PyInstaller does not create application data. If a previous build left it in
# the target, remove it after preserving the backup above as well.
packaged_data=out/'ColorStudio/data'
if packaged_data.exists():shutil.rmtree(packaged_data)
licenses=out/'ColorStudio/THIRD_PARTY';licenses.mkdir(exist_ok=True)
import importlib.metadata
for package_name in ('cryptography','packaging','httpx','httpcore','anyio','certifi','cffi','scipy'):
    distribution=importlib.metadata.distribution(package_name)
    for file in distribution.files or ():
        if 'license' in str(file).casefold() or str(file).casefold().endswith('copying'):
            src=distribution.locate_file(file)
            if src.is_file():
                destination=licenses/package_name/Path(file).name;destination.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(src,destination)
if (source/'doc').exists():shutil.copytree(source/'doc',licenses/'tesseract',dirs_exist_ok=True)
from release_documents import package_documents
package_documents(workspace,out/'ColorStudio')
# Development validation reports remain in the workspace. Distributions
# contain current user documentation and one current verification summary.
print('RELEASE',out/'ColorStudio/ColorStudio.exe')
