def translate(text: str) -> str:
    """把一行简体中文界面文案翻成当前语言。"""
    if not text:
        return text
    table = EXTRA.get(i18n.language)
    if table is not None:
        hit = table.get(text)
        if hit is not None:
            return hit
    # 「（单）」是给英文区分单复数用的内部标记；中文/繁体没有单复数，
    # 直接回退到原文时要把标记去掉，否则会显示成「1 色（单）」。
    return str(i18n.tr(text)).replace('（单）', '').replace('（單）', '')
