"""Build and verify a local candidate, then keep one package in 根目录/发布包."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
from datetime import datetime


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream,'sha256').hexdigest()


def owned_path(root,relative):
    path=root/relative
    if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
        raise ValueError('Package path outside managed directory: '+str(path))
    return path


def deliver(workspace,package,version,evidence):
    """Deliver a verified package; retire only files matching our last inventory."""
    if not re.fullmatch(r'\d+\.\d+\.\d+',version):
        raise ValueError('Invalid local package version')
    workspace=Path(workspace);package=Path(package);evidence=Path(evidence)
    output=workspace/'发布包'
    output.mkdir(exist_ok=True)
    if output.is_symlink() or output.is_junction():
        raise ValueError('Managed package directory must not be redirected')
    evidence.mkdir(parents=True,exist_ok=True)
    catalog=workspace/'.local/local-package.json'
    previous=json.loads(catalog.read_text(encoding='utf-8')) if catalog.exists() else {}
    app=output/'ColorStudio'
    if app.exists() and not previous:
        raise ValueError('Existing program has no local build inventory; preserve it before delivery')
    destination=output/f'ColorStudio-v{version}-Windows-x64.zip'
    if destination.exists():
        if previous.get('zip')!=destination.name or digest(destination)!=previous.get('zip_sha256'):
            raise ValueError('Refusing to replace an unmanaged or modified ZIP')
    for relative in previous.get('files',{}):owned_path(app,relative)
    if previous.get('zip'):owned_path(output,previous['zip'])
    # Create and validate the clean ZIP before transferring any player records.
    archive=Path(shutil.make_archive(str(evidence/f'ColorStudio-v{version}-Windows-x64'),'zip',
                                    root_dir=package.parent,base_dir=package.name))
    from zipfile import ZipFile
    with ZipFile(archive) as zipped:
        if zipped.testzip() is not None:raise ValueError('ZIP integrity check failed')
    files={p.relative_to(package).as_posix():digest(p) for p in package.rglob('*') if p.is_file()}
    # The package inventory never owns data. Carry records into the new runtime
    # only after the distributable ZIP has been completed.
    if (app/'data').exists():
        shutil.copytree(app/'data',package/'data',dirs_exist_ok=True)
    retired=evidence/'previous-program'
    if app.exists():app.rename(retired)
    try:
        shutil.move(str(package),str(app))
    except OSError:
        if retired.exists():retired.rename(app)
        raise
    shutil.move(str(archive),str(destination))
    record=dict(version=version,zip=destination.name,zip_sha256=digest(destination),files=files)
    catalog.parent.mkdir(parents=True,exist_ok=True)
    temporary=catalog.with_suffix('.tmp')
    temporary.write_text(json.dumps(record,ensure_ascii=False,indent=2),encoding='utf-8')
    temporary.replace(catalog)
    cleanup=[]
    # Remove only generated bytes that still match the previous build. Unknown
    # or edited files (including data) remain as records under runtime/.
    if retired.exists():
        for relative,expected in previous.get('files',{}).items():
            path=owned_path(retired,relative)
            if path.is_file() and digest(path)==expected:
                try:path.unlink()
                except OSError:
                    pending=workspace/'待删文件夹'/evidence.name/'ColorStudio'/relative
                    pending.parent.mkdir(parents=True,exist_ok=True)
                    shutil.move(str(path),str(pending))
                cleanup.append(relative)
        for folder in sorted(retired.rglob('*'),key=lambda p:len(p.parts),reverse=True):
            if folder.is_dir():
                try:folder.rmdir()
                except OSError:pass
        if any(retired.iterdir()):
            preserved=workspace/'runtime/local-package-records'/evidence.name
            preserved.parent.mkdir(parents=True,exist_ok=True)
            shutil.move(str(retired),str(preserved))
        else:retired.rmdir()
    old_zip=previous.get('zip')
    if old_zip and old_zip!=destination.name:
        old=owned_path(output,old_zip)
        if old.is_file() and digest(old)==previous.get('zip_sha256'):
            try:old.unlink()
            except OSError:
                pending=workspace/'待删文件夹'/evidence.name/old.name
                pending.parent.mkdir(parents=True,exist_ok=True)
                shutil.move(str(old),str(pending))
            cleanup.append(old_zip)
    (evidence/'delivery.json').write_text(json.dumps(dict(version=version,program=str(app),
        zip=str(destination),zip_sha256=record['zip_sha256'],removed=cleanup),ensure_ascii=False,indent=2),encoding='utf-8')
    return destination


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepared',type=Path,help='Use an already built program directory')
    args=parser.parse_args()
    workspace=Path(__file__).resolve().parents[1]
    sys.path.insert(0,str(workspace/'work/studio'))
    from build_info import APP_VERSION
    evidence=workspace/'artifacts/local-builds'/datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    evidence.mkdir(parents=True)
    package=args.prepared.resolve() if args.prepared else evidence/'staging/ColorStudio'
    if not args.prepared:
        environment=dict(os.environ,COLOR_STUDIO_DIST=str(package.parent),
                         COLOR_STUDIO_UPDATE_PUBLIC_KEYS=str(workspace/'release/update-public-keys.json'))
        with (evidence/'build.log').open('w',encoding='utf-8') as log:
            subprocess.run([sys.executable,str(workspace/'work/studio/build_release.py')],
                           cwd=workspace,env=environment,stdout=log,stderr=subprocess.STDOUT,check=True)
    subprocess.run([sys.executable,str(workspace/'scripts/verify_release.py'),str(package),
                    '--json',str(evidence/'verification.json')],cwd=workspace,check=True)
    print(deliver(workspace,package,APP_VERSION,evidence))


if __name__=='__main__':main()
